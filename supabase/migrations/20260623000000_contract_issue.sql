-- ============================================
-- 1) 현장의 작업자 목록 (effective 현장 기준 — 팀원은 팀장 현장 추종)
-- ============================================
create or replace function yeseong_workers_at_worksite(p_worksite_id uuid)
returns table (id uuid, name text)
language sql
stable
security definer
set search_path = public
as $$
  -- 팀장 미배정: 본인 default_worksite_id
  select w.id, w.name
    from yeseong_workers w
   where w.is_active
     and w.team_leader_id is null
     and w.default_worksite_id = p_worksite_id
  union
  -- 팀원: 팀장 worker행(phone 매칭)의 현장을 추종
  select w.id, w.name
    from yeseong_workers w
    join yeseong_site_managers sm on sm.id = w.team_leader_id
    join yeseong_workers lw on lw.phone = sm.phone
   where w.is_active
     and lw.default_worksite_id = p_worksite_id;
$$;

grant execute on function yeseong_workers_at_worksite(uuid) to authenticated;

