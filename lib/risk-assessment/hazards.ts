// 공종별 유해위험요인·감소대책 표준 라이브러리 (KOSHA 위험성평가 표준모델 근거).
//   빈도(f)·강도(s) 1~3 초안 → 위험성=f×s, 등급 A(6~9)·B(3~4)·C(1~2).
//   위험도는 초안이며 관리자가 현장 실정에 맞게 최종 판정한다.

export type Hazard = {
  risk: string; // 유해위험요인 (잠재 Risk)
  f: number; // 빈도 초안
  s: number; // 강도 초안
  ctrl: string; // 위험 감소대책 (개선대책)
};

export function grade(f: number, s: number): 'A' | 'B' | 'C' {
  const v = f * s;
  return v >= 6 ? 'A' : v >= 3 ? 'B' : 'C';
}

// 공종 키 정규화: 저장값이 "미장(벽미장)" 처럼 세부표기여도 대표 공종으로 매핑
export function normalizeTrade(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const t = raw.replace(/\s/g, '');
  if (t.includes('방수')) return '방수';
  if (t.includes('미장')) return '미장';
  if (t.includes('견출')) return '견출';
  if (t.includes('조적')) return '조적';
  if (t.includes('타일')) return '타일';
  if (t.includes('방통')) return '방통';
  if (t.includes('도장') || t.includes('페인트')) return '도장';
  return null;
}

